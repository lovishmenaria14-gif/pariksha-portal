
import { h, mount, spinner, modal, firstName, fmtDate, fmtDateTime, fmtDuration } from '../dom.js';
import { get } from '../api.js';
import { appHeader, showError } from './shell.js';

function windowChip(e) {
  if (e.windowState === 'upcoming') {
    return h('span', { class: 'chip chip-warn' }, `Opens ${fmtDateTime(e.window.start)}`);
  }

  if (e.windowState === 'closed') {
    return h('span', { class: 'chip chip-danger' }, 'Closed');
  }

  return h('span', { class: 'chip' }, `Open until ${fmtDate(e.window.end)}`);
}


function admitCard(user, e) {
  const row = (label, value) =>
    h('div', { class: 'admit-detail' },
      h('span', null, label),
      h('strong', null, value || 'Not provided')
    );

  const photo = h(
    'div',
    { class: 'admit-photo' },
    h('strong', null, 'PHOTO'),
    h('span', null, 'Not uploaded')
  );

  const signature = h(
    'div',
    { class: 'admit-signature' },
    h('strong', null, 'CANDIDATE SIGNATURE'),
    h('span', null, '________________')
  );

  const card = h(
    'article',
    { class: 'admit-print-card' },

    h('div', { class: 'admit-topline' },
      h('span', null, 'PARIKSHA PORTAL'),
      h('span', null, 'DEMO EXAMINATION')
    ),

    h('header', { class: 'admit-heading' },
      h('div', { class: 'admit-brand-mark' }, 'P'),
      h('div', null,
        h('h1', null, 'PARIKSHA'),
        h('p', null, 'Online Examination Portal'),
        h('strong', null, 'ADMIT CARD / HALL TICKET')
      )
    ),

    h('div', { class: 'admit-exam-title' },
      h('span', null, e.code || 'EXAMINATION'),
      h('h2', null, e.title),
      h('p', null, 'Candidate Examination Entry Document')
    ),

    h('div', { class: 'admit-body' },

      h('section', { class: 'admit-candidate' },
        h('div', { class: 'admit-grid' },
          row('Candidate name', user.name),
          row('Application number', user.applicationNo),
          row('Roll number', user.rollNo),
          row('Examination centre', user.centre)
        ),
        h('div', { class: 'admit-photo-area' },
          photo,
          signature
        )
      ),

      h('section', { class: 'admit-section' },
        h('h3', null, 'EXAMINATION DETAILS'),
        h('div', { class: 'admit-grid' },
          row('Examination code', e.code),
          row('Duration', fmtDuration(e.durationMin)),
          row('Total questions', String(e.questionCount)),
          row('Maximum marks', String(e.maxMarks)),
          row('Exam schedule', 'As announced by controller'),
          row('Availability starts', fmtDateTime(e.window.start)),
          row('Availability closes', fmtDateTime(e.window.end))
        )
      ),

      h('section', { class: 'admit-section' },
        h('h3', null, 'IMPORTANT INSTRUCTIONS'),
        h('ol', { class: 'admit-instructions' },
          h('li', null, 'Carry this admit card when appearing for the examination.'),
          h('li', null, 'Verify your application number and candidate details before the examination.'),
          h('li', null, 'Use your own registered login credentials.'),
          h('li', null, 'Follow the instructions given by the examination controller.'),
          h('li', null, 'Electronic devices and unauthorised assistance are prohibited during the examination.'),
          h('li', null, 'Reach the examination centre according to the schedule communicated by the controller.')
        )
      ),

      h('div', { class: 'admit-signatures' },
        h('div', null, 'Candidate signature'),
        h('div', null, 'Invigilator signature')
      )
    ),

    h('footer', { class: 'admit-footer' },
      h('strong', null, 'IMPORTANT'),
      h('p', null,
        'This is a demonstration admit card generated by Pariksha Portal. ' +
        'It is not issued or endorsed by the National Testing Agency (NTA) ' +
        'or any government examination authority.'
      )
    )
  );

  const m = modal({
    title: 'Examination admit card',
    body: card,
    wide: true,
    actions: [
      h('button', {
        class: 'btn btn-ghost',
        type: 'button',
        onclick: () => m.close()
      }, 'Close'),

      h('button', {
        class: 'btn btn-primary',
        type: 'button',
        onclick: () => {
          const restore = () => {
            document.body.classList.remove('admit-print-mode');
          };

          document.body.classList.add('admit-print-mode');
          window.addEventListener('afterprint', restore, { once: true });
          window.print();
        }
      }, 'Print / Save PDF')
    ]
  });
}


function examRow(user, e) {
  const live = e.status === 'in_progress';
  const submitted = e.status === 'submitted';
  const actions = [];

 actions.push(
  h(
    'button',
    {
      class: 'btn btn-ghost',
      type: 'button',
      onclick: () => admitCard(user, e)
    },
    'Admit card'
  )
);

  if (live) {
    actions.push(
      h(
        'a',
        {
          class: 'btn btn-primary',
          href: `#/exam/${e.attemptId}`
        },
        'Resume exam'
      )
    );
  } else if (submitted) {

    if (e.resultsPublished) {
      actions.push(
        h(
          'a',
          {
            class: 'btn btn-ghost',
            href: `#/result/${e.attemptId}`
          },
          'View result'
        )
      );
    } else {
      actions.push(
        h(
          'span',
          {
            class: 'chip chip-lilac'
          },
          'Result not published yet'
        )
      );
    }

    // Reattempt is allowed only while the exam window is open.
    if (e.windowState === 'open') {
      actions.push(
        h(
          'a',
          {
            class: 'btn btn-primary',
            href: `#/instructions/${e.id}`
          },
          'Reattempt exam'
        )
      );
    } else if (e.windowState === 'upcoming') {
      actions.push(
        h('span', { class: 'chip chip-warn' }, `Reattempt opens ${fmtDateTime(e.window.start)}`)
      );
    } else {
      actions.push(
        h('span', { class: 'chip chip-danger' }, 'Reattempt unavailable')
      );
    }

  } else if (e.windowState === 'open') {
    actions.push(
      h(
        'a',
        {
          class: 'btn btn-primary',
          href: `#/instructions/${e.id}`
        },
        'Start exam'
      )
    );
  }

  return h(
    'article',
    {
      class: 'exam-row',
      dataset: {
        live: String(live)
      }
    },
    h(
      'div',
      null,
      h('h3', null, e.title),

      e.description
        ? h('p', { class: 'muted', style: { marginTop: '6px' } }, e.description)
        : null,

      h(
        'div',
        { class: 'exam-meta' },

        live
          ? h('span', { class: 'chip chip-warn' }, 'In progress')
          : null,

        submitted
          ? h('span', { class: 'chip chip-ok' }, 'Submitted')
          : null,

        h('span', { class: 'chip' }, fmtDuration(e.durationMin)),
        h('span', { class: 'chip' }, `${e.questionCount} questions`),
        h('span', { class: 'chip' }, `${e.maxMarks} marks`),

        !live && !submitted
          ? windowChip(e)
          : null
      )
    ),

    h('div', { class: 'exam-actions' }, actions)
  );
}

export async function dashboardView({ root, user }) {
  document.title = 'Your exams | Pariksha';

  mount(
    root,
    appHeader(user),
    h(
      'main',
      { class: 'page' },
      spinner('Loading your exams')
    )
  );

  let data;

  try {
    data = await get('/exams');
  } catch (e) {
    showError(e);

    mount(
      root,
      appHeader(user),
      h(
        'main',
        { class: 'page' },
        h(
          'div',
          { class: 'empty' },
          h('strong', null, 'Your exams did not load'),
          h('p', null, e.message),
          h(
            'button',
            {
              class: 'btn',
              type: 'button',
              onclick: () => location.reload()
            },
            'Try again'
          )
        )
      )
    );

    return;
  }

  const open = data.exams.filter((e) => e.status !== 'submitted');
  const done = data.exams.filter((e) => e.status === 'submitted');

  const live = data.exams.find((e) => e.status === 'in_progress');

  mount(
    root,
    appHeader(user),
    h(
      'main',
      { class: 'page', id: 'main' },

      h(
        'div',
        { class: 'page-head' },
        h('h1', null, `Hi, ${firstName(user.name)}.`),
        h(
          'p',
          { class: 'muted' },
          live
            ? 'You have an exam in progress. Pick up where you left off.'
            : open.length
              ? 'Pick an exam when you are ready. The clock starts only after you begin.'
              : 'You have finished every available exam.'
        ),
        h('a', { class: 'btn btn-primary', href: '#/practice' }, 'Practice questions')
      ),

      open.length
        ? h(
            'section',
            {
              class: 'exam-list',
              'aria-label': 'Available exams'
            },
            open.map((e) => examRow(user, e))
          )
        : h(
            'div',
            { class: 'empty' },
            h('strong', null, 'No exams to take right now'),
            h('p', null, 'New exams appear here when your centre adds them.')
          ),

      done.length
        ? h(
            'section',
            {
              class: 'exam-list',
              'aria-labelledby': 'done-h'
            },
            h('h2', { id: 'done-h' }, 'Finished'),
            done.map((e) => examRow(user, e))
          )
        : null
    )
  );
}
